@pytest.mark.asyncio
async def test_node_sanitizes_team_path_separators(tmp_path):
    """A `team` containing path separators is slugified, not used verbatim in the path."""
    from langchain_core.messages import HumanMessage

    written = {}

    def _write(rel, content):
        written["rel"] = rel
        target = tmp_path / "logs"
        target.mkdir(parents=True, exist_ok=True)
        out = target / rel.split("/")[-1]
        out.write_text(content)
        return out

    state = {
        "messages": [HumanMessage(content="setup")],
        "user_context": UserContext(team="../../../../tmp/evil"),
        "intent": "setup",
        "plan": [_live_step()],
        "current_step": 1,
        "execution_log": [],
        "approval_pending": None,
        "obsidian_docs": [],
        "slack_results": [],
        "error": None,
        "share_channel": None,
        "share_result": None,
        "extracted_urls": [],
        "processed_message_ids": [],
        "run_success": False,
    }

    with (
        patch("agent_ls.graph.nodes.emit_harness.ObsidianVault") as mock_vault_cls,
        patch("agent_ls.graph.nodes.emit_harness.get_settings") as mock_settings,
        patch("agent_ls.graph.nodes.emit_harness.GitSync") as mock_git_cls,
    ):
        mock_vault = MagicMock()
        mock_vault.exists.return_value = False
        mock_vault.write.side_effect = _write
        mock_vault.root = tmp_path
        mock_vault_cls.return_value = mock_vault

        _patch_settings(mock_settings, git_auto_sync=False)
        mock_git_cls.return_value = MagicMock()

        result = await emit_harness_node(state)

    # No error: the slugified name stays inside logs/.
    assert "error" not in result
    rel = written["rel"]
    # Path separators from the team value are gone; the file is a single name in logs/.
    assert rel.startswith("logs/")
    filename = rel[len("logs/"):]
    assert "/" not in filename
    # Slashes were replaced, so the value can no longer traverse out of logs/.
    assert "tmp_evil" in filename
    assert (tmp_path / rel).resolve().is_relative_to((tmp_path / "logs").resolve())
