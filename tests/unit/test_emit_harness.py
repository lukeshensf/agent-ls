def _live_step() -> PlanStep:
    return PlanStep(
        description="Install node",
        command="brew install node",
        status="done",
        exit_code=0,
        duration_ms=1000,
    )


def _failed_step() -> PlanStep:
    return PlanStep(
        description="Install java",
        command="brew install java",
        status="failed",
        exit_code=1,
    )


def _blocked_step() -> PlanStep:
    return PlanStep(
        description="Wipe disk",
        command="rm -rf /",
        status="failed",
        exit_code=None,
    )


def _manual_step() -> PlanStep:
    return PlanStep(
        description="Request VPN access from IT",
        command=None,
        status="skipped",
    )


