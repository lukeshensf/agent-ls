# --- Serializer tests (pure function, no mocks) ---


def _render(plan, **overrides):
    kwargs = {
        "team": "payments",
        "date": "2026-07-04",
        "source": "reproduced from agent-ls setup run",
        "version": "0.1.0",
        "secrets": [],
    }
    kwargs.update(overrides)
    return render_harness(plan, **kwargs)


def test_header_contains_required_markers():
    out = _render([_live_step()])
    assert out.startswith("#!/usr/bin/env bash\n")
    assert "set -euo pipefail" in out
    assert "# Setup harness for team: payments" in out
    assert "# Date: 2026-07-04" in out
    assert "# Generated by agent-ls v0.1.0" in out
    assert "# Source: reproduced from agent-ls setup run" in out
    assert "auto-generated" in out
    assert out.endswith("\n")


def test_live_step_is_uncommented_with_description_comment():
    out = _render([_live_step()])
    lines = out.splitlines()
    assert "# Install node" in lines
    assert "brew install node" in lines
    # The command line itself is not commented out.
    idx = lines.index("brew install node")
    assert not lines[idx].startswith("#")


def test_failed_step_is_skipped_with_exit_code():
    out = _render([_failed_step()])
    assert "# SKIPPED (failed, exit=1): brew install java" in out
    assert "\nbrew install java\n" not in out


def test_blocked_step_is_commented_blocked():
    out = _render([_blocked_step()])
    assert "# BLOCKED: rm -rf /" in out
    # The dangerous command never appears on its own executable line.
    assert "\nrm -rf /\n" not in out


def test_manual_step_is_commented_manual():
    out = _render([_manual_step()])
    assert "# MANUAL STEP: Request VPN access from IT" in out


def test_other_status_is_skipped_with_status():
    step = PlanStep(
        description="Deferred step",
        command="echo later",
        status="pending",
    )
    out = _render([step])
    assert "# SKIPPED (pending): echo later" in out


def test_secret_is_redacted():
    step = PlanStep(
        description="Auth call",
        command='curl -H "Authorization: Bearer SECRET123" https://api',
        status="done",
        exit_code=0,
    )
    out = _render([step], secrets=["SECRET123"])
    assert "SECRET123" not in out
    assert "***REDACTED***" in out


def test_secret_redacted_in_commented_command():
    step = PlanStep(
        description="Failed auth call",
        command="login --token SECRET123",
        status="failed",
        exit_code=2,
    )
    out = _render([step], secrets=["SECRET123"])
    assert "SECRET123" not in out
    assert "***REDACTED***" in out


def test_secret_redacted_in_description_comment():
    """A token echoed into an LLM-generated description must not leak into the # line."""
    step = PlanStep(
        description="set token to SECRET123 then run",
        command="echo ok",
        status="done",
        exit_code=0,
    )
    out = _render([step], secrets=["SECRET123"])
    assert "SECRET123" not in out
    assert "***REDACTED***" in out


def test_secret_redacted_in_manual_step_description():
    """Manual (command is None) steps render the description twice; both must redact."""
    step = PlanStep(
        description="manually export SECRET123",
        command=None,
        status="pending",
    )
    out = _render([step], secrets=["SECRET123"])
    assert "SECRET123" not in out
    assert "# MANUAL STEP: manually export ***REDACTED***" in out.splitlines()


def test_hostile_multiline_description_cannot_escape_comment():
    step = PlanStep(
        description="safe\nrm -rf /",
        command="echo ok",
        status="done",
        exit_code=0,
    )
    out = _render([step])
    lines = out.splitlines()
    # The injected 'rm -rf /' must not appear as its own executable line.
    assert "rm -rf /" not in lines
    assert "# safe rm -rf /" in lines


def test_empty_plan_is_valid_script_with_no_commands():
    out = _render([])
    assert out.startswith("#!/usr/bin/env bash\n")
    assert "set -euo pipefail" in out
    # No step lines: every line is blank, a comment, the shebang, or the strict-mode line.
    header_lines = {"#!/usr/bin/env bash", "set -euo pipefail"}
    for line in out.splitlines():
        assert line == "" or line.startswith("#") or line in header_lines


def test_large_plan_emits_all_live_commands():
    plan = [
        PlanStep(
            description=f"step {i}",
            command=f"echo step-{i}",
            status="done",
            exit_code=0,
        )
        for i in range(120)
    ]
    out = _render(plan)
    for i in range(120):
        assert f"echo step-{i}" in out


def test_live_command_body_emitted_verbatim():
    step = PlanStep(
        description="Chained install",
        command="brew install x && brew install y | tee log.txt",
        status="done",
        exit_code=0,
    )
    out = _render([step])
    assert "brew install x && brew install y | tee log.txt" in out


